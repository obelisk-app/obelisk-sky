/** "Text channel", "Voice channel" or "Publication" for a channel's kind. */
export function kindLabel(kind: string, w: VillageWords = vw): string {
  return kind === 'forum' ? w.kind.forum : kind.startsWith('voice') ? w.kind.voice : w.kind.text;
}
